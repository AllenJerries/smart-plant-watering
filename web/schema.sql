-- ============================================================================
-- Smart Plant Watering System — Supabase / PostgreSQL schema
-- Run this in the Supabase SQL editor (or with psql) before starting the app.
-- ============================================================================

-- ----------------------------------------------------------------------------
-- Telemetry history
-- ----------------------------------------------------------------------------
create table if not exists public.sensor_readings (
  id           bigint generated by default as identity primary key,
  device_id    text        not null
                           check (char_length(device_id) between 1 and 64),
  moisture_pct numeric(5, 2) not null
                           check (moisture_pct >= 0 and moisture_pct <= 100),
  raw_value    integer     not null
                           check (raw_value >= 0 and raw_value <= 4095),
  rssi         integer     check (rssi is null or (rssi >= -150 and rssi <= 0)),
  created_at   timestamptz not null default now()
);

-- Primary time-series index requested by the dashboard (24 h queries).
create index if not exists sensor_readings_created_at_idx
  on public.sensor_readings (created_at desc);

-- Efficient per-device "latest reading" and 24 h window lookups.
create index if not exists sensor_readings_device_created_at_idx
  on public.sensor_readings (device_id, created_at desc);

comment on table public.sensor_readings is
  'Append-only log of ESP32 soil moisture telemetry.';

-- ----------------------------------------------------------------------------
-- Alert state / hysteresis tracking (one row per device)
-- ----------------------------------------------------------------------------
create table if not exists public.device_state (
  device_id       text primary key
                       check (char_length(device_id) between 1 and 64),
  last_alert_type text not null default 'NORMAL'
                       check (last_alert_type in ('DRY', 'NORMAL', 'FAULT')),
  last_alert_at   timestamptz,
  updated_at      timestamptz not null default now()
);

create index if not exists device_state_last_alert_at_idx
  on public.device_state (last_alert_at desc);

comment on table public.device_state is
  'Last known alert state per device. Used for 6-hour cooldown and hysteresis.';

-- ----------------------------------------------------------------------------
-- Keep updated_at fresh
-- ----------------------------------------------------------------------------
create or replace function public.touch_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists device_state_touch_updated_at on public.device_state;
create trigger device_state_touch_updated_at
  before update on public.device_state
  for each row
  execute function public.touch_updated_at();

-- ----------------------------------------------------------------------------
-- Row Level Security
--
-- The dashboard reads through the anon key (server-side), so read-only access
-- is granted. All writes go through the Next.js API route using the service
-- role key, which bypasses RLS. Never expose the service role key to a browser.
-- ----------------------------------------------------------------------------
alter table public.sensor_readings enable row level security;
alter table public.device_state enable row level security;

drop policy if exists "Public read sensor readings" on public.sensor_readings;
create policy "Public read sensor readings"
  on public.sensor_readings
  for select
  to anon, authenticated
  using (true);

drop policy if exists "Public read device state" on public.device_state;
create policy "Public read device state"
  on public.device_state
  for select
  to anon, authenticated
  using (true);

grant select on public.sensor_readings to anon, authenticated;
grant select on public.device_state to anon, authenticated;

-- ----------------------------------------------------------------------------
-- Realtime
--
-- The dashboard subscribes to INSERTs on sensor_readings and changes on
-- device_state. Both tables must be part of Supabase's realtime publication.
-- This block is idempotent, so schema.sql can be re-run safely.
-- ----------------------------------------------------------------------------
do $$
begin
  if exists (
    select 1 from pg_publication where pubname = 'supabase_realtime'
  ) then
    if not exists (
      select 1
      from pg_publication_tables
      where pubname = 'supabase_realtime'
        and schemaname = 'public'
        and tablename = 'sensor_readings'
    ) then
      execute 'alter publication supabase_realtime add table public.sensor_readings';
    end if;

    if not exists (
      select 1
      from pg_publication_tables
      where pubname = 'supabase_realtime'
        and schemaname = 'public'
        and tablename = 'device_state'
    ) then
      execute 'alter publication supabase_realtime add table public.device_state';
    end if;
  end if;
end $$;
